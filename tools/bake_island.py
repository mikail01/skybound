"""Bake assets/FloatingIslandMap.glb into src/server/Lib/IslandMesh.luau.

The hub rebuilds the island from this data (one flat-coloured triangle per
mesh triangle, colour sampled from the texture atlas), so the island arrives
in Studio through Rojo like any other code, with no 3D import needed.

    python3 tools/bake_island.py   (needs Pillow)
"""

import io
import json
import struct
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "FloatingIslandMap.glb"
OUT = ROOT / "src" / "server" / "Lib" / "IslandMesh.luau"
STANDALONE_TEMPLATE = ROOT / "tools" / "standalone" / "template.luau"
STANDALONE_OUT = ROOT / "tools" / "SpawnOnIsland.server.luau"

data = SRC.read_bytes()
json_len = struct.unpack("<I", data[12:16])[0]
gltf = json.loads(data[20 : 20 + json_len])
bin_start = 20 + json_len
bin_len = struct.unpack("<I", data[bin_start : bin_start + 4])[0]
blob = data[bin_start + 8 : bin_start + 8 + bin_len]

COMPONENTS = {"SCALAR": 1, "VEC2": 2, "VEC3": 3}
FORMATS = {5126: ("f", 4), 5123: ("H", 2), 5125: ("I", 4), 5121: ("B", 1)}


def accessor(index):
    acc = gltf["accessors"][index]
    view = gltf["bufferViews"][acc["bufferView"]]
    n = COMPONENTS[acc["type"]]
    fmt, size = FORMATS[acc["componentType"]]
    stride = view.get("byteStride") or size * n
    base = view.get("byteOffset", 0) + acc.get("byteOffset", 0)
    out = []
    for i in range(acc["count"]):
        values = struct.unpack_from("<" + fmt * n, blob, base + i * stride)
        out.append(values if n > 1 else values[0])
    return out


image_view = gltf["bufferViews"][gltf["images"][0]["bufferView"]]
start = image_view.get("byteOffset", 0)
atlas = Image.open(io.BytesIO(blob[start : start + image_view["byteLength"]])).convert("RGB")
W, H = atlas.size


def sample(uvs):
    u = sum(t[0] for t in uvs) / 3
    v = sum(t[1] for t in uvs) / 3
    x = min(W - 1, max(0, int(u * W)))
    y = min(H - 1, max(0, int(v * H)))
    return "%02x%02x%02x" % atlas.getpixel((x, y))


palette = {}
meshes = []
for node in gltf["nodes"]:
    if "mesh" not in node or node["name"].endswith("_Outline"):
        continue
    verts, vert_index, tris = [], {}, []
    for prim in gltf["meshes"][node["mesh"]]["primitives"]:
        pos = accessor(prim["attributes"]["POSITION"])
        uv = accessor(prim["attributes"]["TEXCOORD_0"])
        idx = accessor(prim["indices"]) if "indices" in prim else list(range(len(pos)))
        for t in range(0, len(idx) - 2, 3):
            corners = idx[t : t + 3]
            ids = []
            for c in corners:
                key = tuple(round(v * 100) for v in pos[c])
                if key not in vert_index:
                    vert_index[key] = len(verts)
                    verts.append(key)
                ids.append(vert_index[key] + 1)
            if len(set(ids)) < 3:
                continue
            color = sample([uv[c] for c in corners])
            if color not in palette:
                palette[color] = len(palette) + 1
            tris.append((*ids, palette[color]))
    meshes.append((node["name"], verts, tris))

lines = [
    "--!strict",
    "-- GENERATED by tools/bake_island.py from assets/FloatingIslandMap.glb. Do not edit.",
    "-- Positions are map units x100; each triangle is three 1-based vertex",
    "-- indices plus a palette index.",
    "",
    "return {",
    "\tpalette = { " + ", ".join('"%s"' % c for c in palette) + " },",
    "\tmeshes = {",
]
for name, verts, tris in meshes:
    lines.append("\t\t{")
    lines.append('\t\t\tname = "%s",' % name)
    lines.append('\t\t\tverts = "%s",' % " ".join("%d %d %d" % v for v in verts))
    lines.append('\t\t\ttris = "%s",' % " ".join("%d %d %d %d" % t for t in tris))
    lines.append("\t\t},")
lines += ["\t},", "}", ""]
OUT.write_text("\n".join(lines))
# The drop-in script embeds the same table (everything after "return ").
table = "\n".join(lines[lines.index("return {") :])[len("return ") :].rstrip()
STANDALONE_OUT.write_text(STANDALONE_TEMPLATE.read_text().replace("--[[DATA]]", table, 1))
total = sum(len(t) for _, _, t in meshes)
print(f"{OUT.relative_to(ROOT)}: {len(meshes)} meshes, {total} triangles, {len(palette)} colours", file=sys.stderr)
